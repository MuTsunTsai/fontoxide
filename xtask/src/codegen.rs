//! Code generation from fontTools definitions.
//!
//! fontTools describes much of its data declaratively: OpenType Layout tables in
//! `otData.py`, fixed-size records as `sstruct` format strings, table classes with
//! their dependencies, and data such as the Adobe Glyph List. `reference.py` exports
//! those to JSON and text files (committed, so upstream changes show up as reviewable
//! diffs), and this module generates Rust code from them.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use serde::Deserialize;

use crate::{reference, root};

fn crates_dir() -> PathBuf {
	root().join("crates")
}

/// Where the exported definitions live.
fn data_dir() -> PathBuf {
	crates_dir().join("fontoxide-ttlib").join("codegen")
}

fn generated_dir() -> PathBuf {
	crates_dir()
		.join("fontoxide-ttlib")
		.join("src")
		.join("generated")
}

#[derive(Deserialize)]
struct OtData {
	fonttools_version: String,
	tables: Vec<serde_json::Value>,
}

#[derive(Deserialize)]
struct Sstruct {
	formats: Vec<serde_json::Value>,
}

#[derive(Deserialize)]
struct Tables {
	tables: Vec<TableInfo>,
}

#[derive(Deserialize)]
struct TableInfo {
	tag: String,
	class: String,
	dependencies: Vec<String>,
}

#[derive(Deserialize)]
struct StandardGlyphOrder {
	names: Vec<String>,
}

pub fn run() -> Result<()> {
	let dir = data_dir();
	let otdata = dir.join("otdata.json");
	let sstruct = dir.join("sstruct.json");

	reference::run(["export-otdata".as_ref(), otdata.as_os_str()])?;
	reference::run(["export-sstruct".as_ref(), sstruct.as_os_str()])?;
	reference::run(["export-data".as_ref(), crates_dir().as_os_str()])?;

	let otdata: OtData = read_json(&otdata)?;
	let sstruct: Sstruct = read_json(&sstruct)?;
	println!(
		"Exported fontTools {} definitions: {} otData structs, {} sstruct formats.",
		otdata.fonttools_version,
		otdata.tables.len(),
		sstruct.formats.len()
	);

	let out = generated_dir();
	std::fs::create_dir_all(&out)?;
	write(&out.join("mod.rs"), &generate_mod())?;
	write(
		&out.join("tables.rs"),
		&generate_tables(&read_json(&dir.join("tables.json"))?),
	)?;
	write(
		&out.join("standard_glyph_order.rs"),
		&generate_standard_glyph_order(&read_json(&dir.join("standardGlyphOrder.json"))?),
	)?;
	write(
		&out.join("cff_strings.rs"),
		&generate_cff_strings(&read_json(&dir.join("cffStrings.json"))?),
	)?;
	let ottables: crate::codegen_ot::OtTables = read_json(&dir.join("ottables.json"))?;
	write(&out.join("ot.rs"), &crate::codegen_ot::generate(&ottables)?)?;
	println!("Generated {}", out.display());

	// Formatting keeps the generated code reviewable and stable.
	let status = std::process::Command::new("rustfmt")
		.arg("--edition")
		.arg("2024")
		.args(
			[
				"mod.rs",
				"tables.rs",
				"standard_glyph_order.rs",
				"cff_strings.rs",
				"ot.rs",
			]
			.map(|f| out.join(f)),
		)
		.status()
		.context("failed to run rustfmt")?;
	anyhow::ensure!(status.success(), "rustfmt failed");
	Ok(())
}

fn read_json<T: serde::de::DeserializeOwned>(path: &Path) -> Result<T> {
	let text =
		std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
	serde_json::from_str(&text).with_context(|| format!("parsing {}", path.display()))
}

fn write(path: &Path, content: &str) -> Result<()> {
	std::fs::write(path, content).with_context(|| format!("writing {}", path.display()))
}

pub(crate) const HEADER: &str =
	"// @generated by `cargo xtask codegen` from fontTools definitions. Do not edit.\n\n";

fn generate_mod() -> String {
	let mut s = String::from(HEADER);
	s.push_str("//! Code generated from fontTools definitions.\n\n");
	s.push_str(
		"pub mod cff_strings;\npub mod ot;\npub mod standard_glyph_order;\npub mod tables;\n",
	);
	s
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct CffStrings {
	standard_encoding: Vec<String>,
	standard_strings: Vec<String>,
	#[serde(rename = "ISOAdobe")]
	iso_adobe: Vec<String>,
	#[serde(rename = "Expert")]
	expert: Vec<String>,
	#[serde(rename = "ExpertSubset")]
	expert_subset: Vec<String>,
}

fn generate_cff_strings(strings: &CffStrings) -> String {
	let mut s = String::from(HEADER);
	s.push_str("//! CFF standard strings and predefined charsets (`fontTools.cffLib`).\n\n");
	let mut list = |doc: &str, name: &str, items: &[String]| {
		let _ = writeln!(s, "/// {doc}");
		let _ = writeln!(s, "pub const {name}: [&str; {}] = [", items.len());
		for n in items {
			let _ = writeln!(s, "\t{n:?},");
		}
		s.push_str("];\n\n");
	};
	list(
		"The CFF standard strings (`cffStandardStrings`).",
		"STANDARD_STRINGS",
		&strings.standard_strings,
	);
	list(
		"The glyph names of the Standard Encoding by code (`StandardEncoding`).",
		"STANDARD_ENCODING",
		&strings.standard_encoding,
	);
	list(
		"The ISOAdobe charset (`cffISOAdobeStrings`).",
		"ISO_ADOBE",
		&strings.iso_adobe,
	);
	list(
		"The Expert charset (`cffIExpertStrings`).",
		"EXPERT",
		&strings.expert,
	);
	list(
		"The ExpertSubset charset (`cffExpertSubsetStrings`).",
		"EXPERT_SUBSET",
		&strings.expert_subset,
	);
	s
}

fn tag_literal(tag: &str) -> String {
	let mut s = String::from("b\"");
	for c in tag.chars() {
		match c {
			'"' | '\\' => {
				s.push('\\');
				s.push(c);
			}
			' '..='~' => s.push(c),
			c => {
				let _ = write!(s, "\\x{:02x}", c as u32);
			}
		}
	}
	s.push('"');
	s
}

fn generate_tables(tables: &Tables) -> String {
	let mut s = String::from(HEADER);
	s.push_str("//! Facts about the fontTools table classes (`fontTools.ttLib.tables`).\n\n");
	s.push_str("use fontoxide_misc::Tag;\n\n");

	s.push_str("/// The tags that fontTools has a table class for.\n");
	let _ = writeln!(
		s,
		"pub const FONTTOOLS_TABLES: [Tag; {}] = [",
		tables.tables.len()
	);
	for t in &tables.tables {
		let _ = writeln!(s, "\tTag::new({}), // {}", tag_literal(&t.tag), t.class);
	}
	s.push_str("];\n\n");

	s.push_str("/// The tables that must be compiled before `tag` (the class-level\n");
	s.push_str("/// `dependencies`).\n");
	s.push_str("pub fn dependencies(tag: Tag) -> &'static [Tag] {\n\tmatch &tag.0 {\n");
	for t in tables.tables.iter().filter(|t| !t.dependencies.is_empty()) {
		let deps: Vec<String> = t
			.dependencies
			.iter()
			.map(|d| format!("Tag::new({})", tag_literal(d)))
			.collect();
		let _ = writeln!(
			s,
			"\t\t{} => {{\n\t\t\tconst D: &[Tag] = &[{}];\n\t\t\tD\n\t\t}}",
			tag_literal(&t.tag),
			deps.join(", ")
		);
	}
	s.push_str("\t\t_ => &[],\n\t}\n}\n");
	s
}

fn generate_standard_glyph_order(order: &StandardGlyphOrder) -> String {
	let mut s = String::from(HEADER);
	s.push_str(
		"//! The standard Macintosh glyph order (`fontTools.ttLib.standardGlyphOrder`).\n\n",
	);
	s.push_str("/// The 258 glyph names of the standard Macintosh glyph order\n");
	s.push_str("/// (`standardGlyphOrder`), used by `post` table formats 1 and 2.\n");
	let _ = writeln!(
		s,
		"pub const STANDARD_GLYPH_ORDER: [&str; {}] = [",
		order.names.len()
	);
	for n in &order.names {
		let _ = writeln!(s, "\t{n:?},");
	}
	s.push_str("];\n");
	s
}
