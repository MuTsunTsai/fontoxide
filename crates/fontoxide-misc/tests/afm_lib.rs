//! `Tests/afmLib/afmLib_test.py`, and the doctest of `fontTools.afmLib`.

use std::path::PathBuf;
use std::sync::atomic::{AtomicUsize, Ordering};

use fontoxide_misc::afm_lib::{Afm, AttrValue};

type TestResult = Result<(), Box<dyn std::error::Error>>;

fn afm_path() -> PathBuf {
	PathBuf::from(env!("CARGO_MANIFEST_DIR"))
		.join("../../upstream/fonttools/Tests/afmLib/data/TestAFM.afm")
}

fn pairs(v: &[(&str, &str)]) -> Vec<(String, String)> {
	v.iter()
		.map(|(a, b)| ((*a).to_owned(), (*b).to_owned()))
		.collect()
}

#[test]
fn test_read_afm() -> TestResult {
	let afm = Afm::open(afm_path())?;
	let mut kernpairs = afm.kernpairs();
	kernpairs.sort();
	let mut expected = pairs(&[
		("V", "A"),
		("T", "comma"),
		("V", "d"),
		("T", "c"),
		("T", "period"),
	]);
	expected.sort();
	assert_eq!(kernpairs, expected);
	assert_eq!(afm.kerning(("V", "A")), Some(-60));
	assert_eq!(afm.kerning(("V", "d")), Some(30));
	assert_eq!(afm.char("A"), Some((65, 668, (8, -25, 660, 666))));
	Ok(())
}

/// `AFMTest.write`: writes the AFM, then reads it back.
fn write(afm: &Afm, sep: &str) -> Result<(Afm, String), Box<dyn std::error::Error>> {
	static N: AtomicUsize = AtomicUsize::new(0);
	let temp = std::env::temp_dir().join(format!(
		"fontoxide-misc-afm-lib-{}-{}.afm",
		std::process::id(),
		N.fetch_add(1, Ordering::SeqCst)
	));
	let result = (|| -> Result<(Afm, String), Box<dyn std::error::Error>> {
		afm.write(&temp, sep)?;
		// Universal newlines, like `open(temp, "r")`.
		let data = std::fs::read_to_string(&temp)?
			.replace("\r\n", "\n")
			.replace('\r', "\n");
		Ok((Afm::open(&temp)?, data))
	})();
	let _ = std::fs::remove_file(&temp);
	result
}

#[test]
fn test_write_afm() -> TestResult {
	let afm = Afm::open(afm_path())?;
	let (new_afm, afm_data) = write(&afm, "\r")?;
	assert_eq!(afm.kernpairs(), new_afm.kernpairs());
	assert_eq!(afm.chars(), new_afm.chars());
	// skip the "generated by afmLib" comment
	assert_eq!(afm.comments(), &new_afm.comments()[1..]);
	for pair in afm.kernpairs() {
		let pair = (pair.0.as_str(), pair.1.as_str());
		assert_eq!(afm.kerning(pair), new_afm.kerning(pair));
	}
	for c in afm.chars() {
		assert_eq!(afm.char(&c), new_afm.char(&c));
	}
	let original = std::fs::read_to_string(afm_path())?
		.replace("\r\n", "\n")
		.replace('\r', "\n");
	let original_lines: Vec<&str> = original.lines().collect();
	let mut new_lines: Vec<&str> = afm_data.lines().collect();
	new_lines.remove(1); // remove the "generated by afmLib" comment
	assert_eq!(original_lines, new_lines);
	Ok(())
}

/// The output is byte for byte the input file, but for the comment with the
/// time.
#[test]
fn write_is_byte_identical() -> TestResult {
	let afm = Afm::open(afm_path())?;
	// The line ends of the checked out file depend on the Git settings.
	let original = std::fs::read_to_string(afm_path())?
		.replace("\r\n", "\n")
		.replace('\r', "\n");
	let mut lines: Vec<&str> = original.lines().collect();
	let text = afm.to_text("\r", "01/02/2026 03:04:05");
	lines.insert(1, "Comment Generated by afmLib; at 01/02/2026 03:04:05");
	assert_eq!(text, lines.join("\r") + "\r");
	Ok(())
}

/// The doctest of the module.
#[test]
fn afm_lib_doctest() -> TestResult {
	let mut f = Afm::open(afm_path())?;
	// Accessing a pair gets you the kern value
	assert_eq!(f.kerning(("V", "A")), Some(-60));
	// Accessing a glyph name gets you metrics
	assert_eq!(f.char("A"), Some((65, 668, (8, -25, 660, 666))));
	// Accessing an attribute gets you metadata
	let s = |v: &str| Some(AttrValue::Str(v.to_owned()));
	assert_eq!(f.attr("FontName").cloned(), s("TestFont-Regular"));
	assert_eq!(f.attr("FamilyName").cloned(), s("TestFont"));
	assert_eq!(f.attr("Weight").cloned(), s("Regular"));
	assert_eq!(f.attr("XHeight"), Some(&AttrValue::Int(500)));
	assert_eq!(f.attr("Ascender"), Some(&AttrValue::Int(750)));
	// Attributes and items can also be set
	f.set_kerning(("A", "V"), -150); // Tighten kerning
	f.set_attr("FontName", AttrValue::Str("TestFont Squished".into()));
	assert_eq!(f.kerning(("A", "V")), Some(-150));
	Ok(())
}
