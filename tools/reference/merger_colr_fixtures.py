"""Generates crates/fontoxide-varlib/tests/merger_colr/cases.rs.

The class COLRVariationMergerTest of Tests/varLib/merger_test.py is parametrized with
about 1800 lines of colorLib paint data. This script reads the parameters from the test
module and writes them as Rust: the paints as fontoxide-colorlib `Value`s (built with the
helpers `i`, `f`, `s`, `l` and `m` of the test), the expected TTX lines and the expected
`varIdxes`.

    uv run --project tools/reference python tools/reference/merger_colr_fixtures.py
"""

import json
import subprocess
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "upstream" / "fonttools" / "Lib"))
sys.path.insert(0, str(ROOT / "upstream" / "fonttools" / "Tests" / "varLib"))
sys.dont_write_bytecode = True

import merger_test  # noqa: E402

OUT = ROOT / "crates" / "fontoxide-varlib" / "tests" / "merger_colr" / "cases.rs"


def rust_str(s):
    return json.dumps(s, ensure_ascii=False)


def value(v, indent):
    pad = "\t" * indent
    if isinstance(v, bool):
        raise TypeError(v)
    if isinstance(v, int):
        return f"i({int(v)})"
    if isinstance(v, float):
        r = repr(v)
        if "inf" in r or "nan" in r:
            raise ValueError(v)
        return f"f({r})"
    if isinstance(v, str):
        return f"s({rust_str(v)})"
    if isinstance(v, (list, tuple)):
        if not v:
            return "l(vec![])"
        items = "".join(f"{pad}\t{value(x, indent + 1)},\n" for x in v)
        return f"l(vec![\n{items}{pad}])"
    if isinstance(v, dict):
        if not v:
            return "m(vec![])"
        items = "".join(
            f"{pad}\t({rust_str(str(k))}, {value(x, indent + 1)}),\n" for k, x in v.items()
        )
        return f"m(vec![\n{items}{pad}])"
    raise TypeError(type(v))


def strs(lines, indent):
    pad = "\t" * indent
    items = "".join(f"{pad}\t{rust_str(x)},\n" for x in lines)
    return f"&[\n{items}{pad}]"


def ints(values):
    return "&[" + ", ".join(str(int(x)) for x in values) + "]"


def params(func, argnames):
    for mark in func.pytestmark:
        names = [n.strip() for n in mark.args[0].split(",")]
        if names == argnames:
            return mark.args[1]
    raise KeyError(argnames)


def main():
    cls = merger_test.COLRVariationMergerTest
    out = [
        "// Generated by tools/reference/merger_colr_fixtures.py from the parameters of",
        "// COLRVariationMergerTest in Tests/varLib/merger_test.py. Do not edit.",
        "",
        "use super::{ExpandCase, FullTableCase, MergePaintCase, f, i, l, m, s};",
        "",
        "pub(crate) fn merge_paint_cases() -> Vec<MergePaintCase> {",
        "\tvec![",
    ]
    for p in params(cls.test_merge_Paint, ["paints", "expected_xml", "expected_varIdxes"]):
        paints, xml, idxes = p.values
        out.append("\t\tMergePaintCase {")
        out.append(f"\t\t\tid: {rust_str(p.id)},")
        out.append(f"\t\t\tpaints: vec![")
        for paint in paints:
            out.append(f"\t\t\t\t{value(paint, 4)},")
        out.append("\t\t\t],")
        out.append(f"\t\t\texpected_xml: {strs(xml, 3)},")
        out.append(f"\t\t\texpected_var_idxes: {ints(idxes)},")
        out.append("\t\t},")
    out += ["\t]", "}", ""]

    out += ["pub(crate) fn full_table_cases() -> Vec<FullTableCase> {", "\tvec!["]
    for p in params(
        cls.test_merge_full_table,
        ["color_glyphs", "output_layer_reuse", "expected_xml", "expected_varIdxes"],
    ):
        color_glyphs, output_layer_reuse, xml, idxes = p.values
        out.append("\t\tFullTableCase {")
        out.append(f"\t\t\tid: {rust_str(p.id)},")
        out.append("\t\t\tcolor_glyphs: vec![")
        for glyphs in color_glyphs:
            items = "".join(
                f"\t\t\t\t\t({rust_str(k)}, {value(v, 5)}),\n" for k, v in glyphs.items()
            )
            out.append(f"\t\t\t\tvec![\n{items}\t\t\t\t],")
        out.append("\t\t\t],")
        out.append(f"\t\t\toutput_layer_reuse: {'true' if output_layer_reuse else 'false'},")
        out.append(f"\t\t\texpected_xml: {strs(xml, 3)},")
        out.append(f"\t\t\texpected_var_idxes: {ints(idxes)},")
        out.append("\t\t},")
    out += ["\t]", "}", ""]

    out += ["pub(crate) fn expand_cases() -> Vec<ExpandCase> {", "\tvec!["]
    for p in params(
        cls.test_expandPaintColrLayers, ["color_glyphs", "before_xml", "expected_xml"]
    ):
        color_glyphs, before, xml = p.values
        out.append("\t\tExpandCase {")
        out.append(f"\t\t\tid: {rust_str(p.id)},")
        items = "".join(
            f"\t\t\t\t({rust_str(k)}, {value(v, 4)}),\n" for k, v in color_glyphs.items()
        )
        out.append(f"\t\t\tcolor_glyphs: vec![\n{items}\t\t\t],")
        out.append(f"\t\t\tbefore_xml: {strs(before, 3)},")
        out.append(f"\t\t\texpected_xml: {strs(xml, 3)},")
        out.append("\t\t},")
    out += ["\t]", "}", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)


if __name__ == "__main__":
    main()
