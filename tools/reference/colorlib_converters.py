"""Generate the converter tables of fontoxide-colorlib from fontTools' otData.

`fontTools.colorLib.table_builder` builds otTables reflectively from their
converters. fontoxide has no reflection, so this script writes the converters
of the COLR paint graph classes, and the code that moves converted values into
the typed structs of fontoxide-ttlib and back, as Rust:

	uv run --project tools/reference python tools/reference/colorlib_converters.py \
		crates/fontoxide-colorlib/src/generated.rs
"""

import sys
from pathlib import Path

sys.dont_write_bytecode = True
UPSTREAM = Path(__file__).resolve().parents[2] / "upstream" / "fonttools"
sys.path.insert(0, str(UPSTREAM / "Lib"))

import fontTools  # noqa: E402
from fontTools.ttLib.tables import otTables as ot  # noqa: E402
from fontTools.ttLib.tables import otConverters as oc  # noqa: E402
from fontTools.ttLib.tables.otBase import FormatSwitchingBaseTable  # noqa: E402

# The classes that colorLib builds: the paint graph of COLRv1.
CLASSES = [
	"Paint",
	"ColorLine",
	"VarColorLine",
	"ColorStop",
	"VarColorStop",
	"Affine2x3",
	"VarAffine2x3",
	"ClipBox",
]

INT_TYPES = {
	"UInt8": "u8",
	"UShort": "u16",
	"Short": "i16",
	"ULong": "u32",
	"VarIndex": "u32",
}


def snake(name: str) -> str:
	"""Same as `snake` of xtask/src/codegen_ot.rs."""
	out = ""
	for i, c in enumerate(name):
		if c.isascii() and c.isupper():
			prev = name[i - 1] if i > 0 else None
			nxt = name[i + 1] if i + 1 < len(name) else None
			if prev is None:
				boundary = False
			elif prev.islower() or prev.isdigit():
				boundary = True
			elif prev.isupper():
				boundary = nxt is not None and nxt.islower()
			else:
				boundary = False
			if boundary and not out.endswith("_"):
				out += "_"
			out += c.lower()
		else:
			out += c
	return out


def describe(conv):
	"""(conv expression, assemble expression, unbuild expression) of a converter."""
	name = conv.name
	field = snake(name)
	enum = getattr(conv, "enumClass", None)
	if enum:
		enum_name = enum.__name__
		return (
			f"Conv::Enum(EnumType::{enum_name})",
			f"o.int_field::<u8>({name!r}, IntType::UInt8)?",
			f"Out::Enum(EnumType::{enum_name}, t.{field})",
		)
	if isinstance(conv, oc.ComputedInt):
		return None
	if isinstance(conv, oc.IntValue):
		kind = type(conv).__name__
		rust = INT_TYPES[kind]
		int_type = "ULong" if kind == "VarIndex" else kind
		default = ""
		if isinstance(conv, oc.OptionalValue):
			default = f", default: Some({conv.DEFAULT})"
		return (
			f"Conv::Int(IntType::{int_type}){default}",
			f"o.int_field::<{rust}>({name!r}, IntType::{int_type})?",
			f"Out::Int(i64::from(t.{field}))",
		)
	if isinstance(conv, oc.FloatValue):
		return (
			"Conv::Float",
			f"o.float_field({name!r})?",
			f"Out::Float(t.{field})",
		)
	if isinstance(conv, oc.GlyphID):
		return (
			"Conv::Glyph",
			f"o.glyph_field({name!r}, glyphs)?",
			f"Out::Glyph(t.{field})",
		)
	if isinstance(conv, oc.Struct):
		cls = conv.tableClass.__name__
		assert cls in CLASSES, cls
		if conv.repeat:
			return (
				f"Conv::Repeat(Class::{cls}, {conv.repeat!r})",
				f"o.tables_field::<ot::{cls}>({name!r})?",
				f"Out::Tables(t.{field}.iter().map(TableRef::{cls}).collect())",
			)
		return (
			f"Conv::Struct(Class::{cls})",
			f"Some(Box::new(o.table_field::<ot::{cls}>({name!r})?))",
			f"Out::Table(t.{field}.as_deref().map(TableRef::{cls}))",
		)
	raise NotImplementedError(f"{type(conv).__name__} {name}")


def field_lists(cls):
	"""[(format or None, converters)]."""
	if issubclass(cls, FormatSwitchingBaseTable):
		return sorted(cls.converters.items())
	return [(None, cls.converters)]


def main(out_path: str) -> None:
	lines = []
	w = lines.append
	w(f"//! The converters of the `COLR` classes that `TableBuilder` builds, from")
	w(f"//! fontTools {fontTools.version}. Generated by")
	w("//! `tools/reference/colorlib_converters.py`; do not edit.")
	w("")
	w("#![allow(clippy::too_many_lines)]")
	w("")
	w("use fontoxide_ttlib::ot::types as ot;")
	w("")
	w("use crate::Result;")
	w("use crate::table_builder::{Conv, EnumType, Field, GlyphIds, IntType, Obj, Out, UnbuiltFields};")
	w("")

	# Class and Table enums.
	w("/// An otTables class that `TableBuilder` can build.")
	w("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")
	w("pub enum Class {")
	for name in CLASSES:
		w(f"\t/// `ot.{name}`.")
		w(f"\t{name},")
	w("}")
	w("")
	w("impl Class {")
	w("\t/// The class name.")
	w("\tpub fn name(self) -> &'static str {")
	w("\t\tmatch self {")
	for name in CLASSES:
		w(f'\t\t\tClass::{name} => "{name}",')
	w("\t\t}")
	w("\t}")
	w("")
	w("\t/// The formats of a format-switching class (`FormatSwitchingBaseTable`).")
	w("\tpub fn formats(self) -> Option<&'static [u16]> {")
	w("\t\tmatch self {")
	for name in CLASSES:
		cls = getattr(ot, name)
		if issubclass(cls, FormatSwitchingBaseTable):
			fmts = ", ".join(str(f) for f, _ in field_lists(cls))
			w(f"\t\t\tClass::{name} => Some(&[{fmts}]),")
	w("\t\t\t_ => None,")
	w("\t\t}")
	w("\t}")
	w("")
	w("\t/// The assignable converters (`_assignable(convertersByName)`), in")
	w("\t/// declaration order, of a class or one of its formats.")
	w("\tpub(crate) fn fields(self, format: Option<u16>) -> Option<&'static [Field]> {")
	w("\t\tmatch (self, format) {")
	for name in CLASSES:
		cls = getattr(ot, name)
		for fmt, convs in field_lists(cls):
			pat = f"Some({fmt})" if fmt is not None else "None"
			const = snake(name).upper() + (f"_{fmt}" if fmt is not None else "")
			w(f"\t\t\t(Class::{name}, {pat}) => Some({const}),")
	w("\t\t\t_ => None,")
	w("\t\t}")
	w("\t}")
	w("}")
	w("")

	w("/// A built table of one of the [`Class`]es.")
	w("#[derive(Debug, Clone, PartialEq)]")
	w("pub enum Table {")
	for name in CLASSES:
		w(f"\t/// `ot.{name}`.")
		w(f"\t{name}(ot::{name}),")
	w("}")
	w("")
	w("impl Table {")
	w("\t/// The class of the table.")
	w("\tpub fn class(&self) -> Class {")
	w("\t\tmatch self {")
	for name in CLASSES:
		w(f"\t\t\tTable::{name}(_) => Class::{name},")
	w("\t\t}")
	w("\t}")
	w("}")
	w("")
	w("/// A reference to a built table, for unbuilding.")
	w("#[derive(Debug, Clone, Copy)]")
	w("pub enum TableRef<'a> {")
	for name in CLASSES:
		w(f"\t/// `ot.{name}`.")
		w(f"\t{name}(&'a ot::{name}),")
	w("}")
	w("")
	w("impl<'a> From<&'a Table> for TableRef<'a> {")
	w("\tfn from(table: &'a Table) -> Self {")
	w("\t\tmatch table {")
	for name in CLASSES:
		w(f"\t\t\tTable::{name}(t) => TableRef::{name}(t),")
	w("\t\t}")
	w("\t}")
	w("}")
	w("")
	w("/// Typed tables that a [`Table`] holds.")
	w("pub trait FromTable: Sized {")
	w("\t/// The class of the type.")
	w("\tconst CLASS: Class;")
	w("\t/// The typed table, or the table back if it is of another class.")
	w("\tfn from_table(table: Table) -> std::result::Result<Self, Table>;")
	w("\t/// Wraps the typed table.")
	w("\tfn into_table(self) -> Table;")
	w("}")
	w("")
	for name in CLASSES:
		w(f"impl FromTable for ot::{name} {{")
		w(f"\tconst CLASS: Class = Class::{name};")
		w("\tfn from_table(table: Table) -> std::result::Result<Self, Table> {")
		w("\t\tmatch table {")
		w(f"\t\t\tTable::{name}(t) => Ok(t),")
		if len(CLASSES) > 1:
			w("\t\t\tother => Err(other),")
		w("\t\t}")
		w("\t}")
		w("\tfn into_table(self) -> Table {")
		w(f"\t\tTable::{name}(self)")
		w("\t}")
		w("}")
		w("")

	# Field tables.
	for name in CLASSES:
		cls = getattr(ot, name)
		for fmt, convs in field_lists(cls):
			const = snake(name).upper() + (f"_{fmt}" if fmt is not None else "")
			w(f"const {const}: &[Field] = &[")
			for conv in convs:
				d = describe(conv)
				if d is None:
					continue
				conv_expr = d[0]
				default = ""
				if ", default: " in conv_expr:
					conv_expr, default = conv_expr.split(", default: ")
					default = f", default: {default}"
				else:
					default = ", default: None"
				w(f"\tField {{ name: {conv.name!r}, conv: {conv_expr}{default} }},".replace("'", '"'))
			w("];")
			w("")

	# Assembly.
	w("/// Moves the converted attributes of `o` into the typed table of its class")
	w("/// and format.")
	w("pub(crate) fn assemble(o: &mut Obj, glyphs: &GlyphIds) -> Result<Table> {")
	w("\tOk(match (o.class, o.format) {")
	for name in CLASSES:
		cls = getattr(ot, name)
		switching = issubclass(cls, FormatSwitchingBaseTable)
		for fmt, convs in field_lists(cls):
			pat = f"Some({fmt})" if fmt is not None else "None"
			struct = f"{name}Format{fmt}" if switching else name
			w(f"\t\t(Class::{name}, {pat}) => {{")
			w(f"\t\t\tlet t = ot::{struct} {{")
			for conv in convs:
				field = snake(conv.name)
				if isinstance(conv, oc.ComputedInt):
					w(f"\t\t\t\t{field}: o.count_field({conv.name!r})?,".replace("'", '"'))
					continue
				w(f"\t\t\t\t{field}: {describe(conv)[1]},".replace("'", '"'))
			w("\t\t\t};")
			if switching:
				w(f"\t\t\tTable::{name}(ot::{name}::Format{fmt}(t))")
			else:
				w(f"\t\t\tTable::{name}(t)")
			w("\t\t}")
	w("\t\t_ => return Err(o.invalid_format()),")
	w("\t})")
	w("}")
	w("")

	# Unbuilding.
	w("/// The format and the assignable fields of a built table, in converter order;")
	w("/// `None` for a format that fontTools does not know.")
	w("pub(crate) fn unbuild_fields(table: TableRef<'_>) -> Option<UnbuiltFields<'_>> {")
	w("\tSome(match table {")
	for name in CLASSES:
		cls = getattr(ot, name)
		switching = issubclass(cls, FormatSwitchingBaseTable)
		if switching:
			for fmt, convs in field_lists(cls):
				w(f"\t\tTableRef::{name}(ot::{name}::Format{fmt}(t)) => (")
				w(f"\t\t\tSome({fmt}),")
				w("\t\t\tvec![")
				for conv in convs:
					d = describe(conv)
					if d is None:
						continue
					w(f"\t\t\t\t({conv.name!r}, {d[2]}),".replace("'", '"'))
				w("\t\t\t],")
				w("\t\t),")
			w(f"\t\tTableRef::{name}(ot::{name}::Unknown(_)) => return None,")
		else:
			w(f"\t\tTableRef::{name}(t) => (")
			w("\t\t\tNone,")
			w("\t\t\tvec![")
			for conv in field_lists(cls)[0][1]:
				d = describe(conv)
				if d is None:
					continue
				w(f"\t\t\t\t({conv.name!r}, {d[2]}),".replace("'", '"'))
			w("\t\t\t],")
			w("\t\t),")
	w("\t})")
	w("}")
	w("")

	# Shallow copies of paints.
	w("/// A copy of a paint without its child paints (the `Paint` fields are")
	w("/// `None`), so that rebuilding a paint graph does not copy subgraphs.")
	w("pub(crate) fn paint_without_children(paint: &ot::Paint) -> ot::Paint {")
	w("\tmatch paint {")
	for fmt, convs in field_lists(ot.Paint):
		w(f"\t\tot::Paint::Format{fmt}(t) => ot::Paint::Format{fmt}(ot::PaintFormat{fmt} {{")
		for conv in convs:
			field = snake(conv.name)
			if isinstance(conv, oc.Struct) and conv.tableClass is ot.Paint:
				w(f"\t\t\t{field}: None,")
			elif isinstance(conv, oc.Struct):
				w(f"\t\t\t{field}: t.{field}.clone(),")
			else:
				w(f"\t\t\t{field}: t.{field},")
		w("\t\t}),")
	w("\t\tot::Paint::Unknown(f) => ot::Paint::Unknown(*f),")
	w("\t}")
	w("}")
	w("")

	text = "\n".join(lines)
	Path(out_path).write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
	main(sys.argv[1])
