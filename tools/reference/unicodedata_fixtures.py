"""Generates crates/fontoxide-unicodedata/src/ucd.rs from fontTools.unicodedata.

fontTools ships the Unicode Script, Script_Extensions and Blocks properties as
Python modules (Scripts.py, ScriptExtensions.py, Blocks.py, generated by
MetaTools/buildUCD.py). This script exports the same tables as Rust constants:

- SCRIPT_RANGES / SCRIPT_VALUES: the start of each range and its script code;
- SCRIPT_NAMES: script code -> long name (with underscores), sorted by code;
- SCRIPT_EXTENSION_RANGES / SCRIPT_EXTENSION_VALUES: the same for
  Script_Extensions, `None` where the Script property applies, the sets sorted;
- BLOCK_RANGES / BLOCK_VALUES: the same for blocks.

    uv run --project tools/reference python tools/reference/unicodedata_fixtures.py
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "upstream" / "fonttools" / "Lib"))
sys.dont_write_bytecode = True

from fontTools.unicodedata import Blocks, ScriptExtensions, Scripts

OUT = ROOT / "crates" / "fontoxide-unicodedata" / "src" / "ucd.rs"


def rust_str(s):
	assert '"' not in s and "\\" not in s
	return '"%s"' % s


def ranges(name, values):
	lines = [f"pub(crate) const {name}: &[u32] = &["]
	lines += [f"\t0x{v:04X}," for v in values]
	lines.append("];")
	return lines


def main():
	out = [
		"//! Unicode Script, Script_Extensions and Blocks data of `fontTools.unicodedata`",
		"//! (`Scripts`, `ScriptExtensions` and `Blocks`), generated by",
		"//! `tools/reference/unicodedata_fixtures.py`. Do not edit.",
		"",
	]
	out += ranges("SCRIPT_RANGES", Scripts.RANGES)
	out.append("")
	out.append("pub(crate) const SCRIPT_VALUES: &[&str] = &[")
	out += [f"\t{rust_str(v)}," for v in Scripts.VALUES]
	out.append("];")
	out.append("")
	out.append("pub(crate) const SCRIPT_NAMES: &[(&str, &str)] = &[")
	out += [f"\t({rust_str(k)}, {rust_str(Scripts.NAMES[k])})," for k in sorted(Scripts.NAMES)]
	out.append("];")
	out.append("")
	out += ranges("SCRIPT_EXTENSION_RANGES", ScriptExtensions.RANGES)
	out.append("")
	out.append("pub(crate) const SCRIPT_EXTENSION_VALUES: &[Option<&[&str]>] = &[")
	for v in ScriptExtensions.VALUES:
		if v is None:
			out.append("\tNone,")
		else:
			out.append("\tSome(&[%s])," % ", ".join(rust_str(s) for s in sorted(v)))
	out.append("];")
	out.append("")
	out += ranges("BLOCK_RANGES", Blocks.RANGES)
	out.append("")
	out.append("pub(crate) const BLOCK_VALUES: &[&str] = &[")
	out += [f"\t{rust_str(v)}," for v in Blocks.VALUES]
	out.append("];")
	OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
	print(f"wrote {OUT}")


if __name__ == "__main__":
	main()
